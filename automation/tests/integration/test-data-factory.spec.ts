import { expect, test } from '@playwright/test';

import { testTags } from '../../config/test-tags';
import { createAddressData } from '../../test-data/factories/address.factory';
import { createUserData } from '../../test-data/factories/user.factory';
import { invalidEmailScenarios } from '../../test-data/invalid/user.invalid';

test.describe('AgenticQA Nexus test-data factories', () => {
  test(
    'CFG-005 | user factory | generates independent synthetic users',
    {
      tag: [testTags.integration],
    },
    async () => {
      const firstUser = createUserData();
      const secondUser = createUserData();

      expect(firstUser.email).not.toBe(secondUser.email);
      expect(firstUser.firstName).toBeTruthy();
      expect(firstUser.lastName).toBeTruthy();
      expect(firstUser.password).toBeTruthy();
    },
  );

  test(
    'CFG-006 | user factory | supports deterministic overrides',
    {
      tag: [testTags.integration],
    },
    async () => {
      const user = createUserData({
        firstName: 'BoundaryUser',
        email: 'boundary.user@example.test',
      });

      expect(user.firstName).toBe('BoundaryUser');
      expect(user.email).toBe('boundary.user@example.test');

      // Non-overridden fields should still be generated by the factory.
      expect(user.lastName).toBeTruthy();
    },
  );

  test(
    'CFG-007 | address factory | supports deterministic country data',
    {
      tag: [testTags.integration],
    },
    async () => {
      const address = createAddressData();

      expect(address.addressLine1).toBeTruthy();
      expect(address.city).toBeTruthy();
      expect(address.country).toBe('United States');
    },
  );

  test(
    'CFG-008 | invalid data | exposes deterministic negative scenarios',
    {
      tag: [testTags.integration, testTags.negative],
    },
    async () => {
      expect(invalidEmailScenarios.length).toBeGreaterThan(0);

      for (const scenario of invalidEmailScenarios) {
        expect(scenario.caseId).toMatch(/^REG-NEG-\d{3}$/);
        expect(scenario.description).toBeTruthy();
      }
    },
  );
});
